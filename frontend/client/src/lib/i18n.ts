export function getStoredLocale(): Locale {
  if (typeof window === "undefined") return "en";
  const requestedLocale = new URLSearchParams(window.location.search).get("lang");
  if (requestedLocale === "sw" || requestedLocale === "en") return requestedLocale;
  return window.localStorage.getItem("vetkonnect_locale") === "sw" ? "sw" : "en";
}

export function localizeText(value: string, locale: Locale): string {
  const dictionary = locale === "sw" ? phrases : swahiliToEnglish;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const phrase = value.trim();
  const direct = dictionary[phrase];
  if (direct) return `${leading}${direct}${trailing}`;
  if (locale === "sw") {
    const step = phrase.match(/^Step (\d+) of (\d+)$/); if (step) return `${leading}Hatua ya ${step[1]} kati ya ${step[2]}${trailing}`;
    const prepared = phrase.match(/^Your (.+) space is prepared\.$/); if (prepared) return `${leading}Nafasi yako ya ${prepared[1]} iko tayari.${trailing}`;
  } else {
    const step = phrase.match(/^Hatua ya (\d+) kati ya (\d+)$/); if (step) return `${leading}Step ${step[1]} of ${step[2]}${trailing}`;
    const prepared = phrase.match(/^Nafasi yako ya (.+) iko tayari\.$/); if (prepared) return `${leading}Your ${prepared[1]} space is prepared.${trailing}`;
  }
  return value;
}

